void vantage_kernel_panic(panic_code_t code, const char *details) {

  portDISABLE_INTERRUPTS();

  const char *title = "KERNEL PANIC";
  const uint8_t *icon = ICON_SKULL;
  uint16_t bg_color = 0x8000;
  uint16_t fg_color = 0xFFFF;

  switch (code) {
  case PANIC_GURU_MEDITATION:
    title = "GURU MEDITATION";
    icon = ICON_GURU;
    bg_color = 0x0000;
    fg_color = 0xF800;
    break;
  case PANIC_BROWNOUT_DETECTED:
    title = "BROWNOUT DETECTED";
    icon = ICON_LIGHTNING;
    bg_color = 0x8400;
    fg_color = 0xFFE0;
    break;
  case PANIC_OUT_OF_MEMORY:
    title = "OUT OF MEMORY";
    icon = ICON_SKULL;
    bg_color = 0x0010;
    fg_color = 0x07FF;
    break;
  case PANIC_STORAGE_FAILURE:
    title = "STORAGE FAILURE";
    icon = ICON_SKULL;
    bg_color = 0x4000;
    fg_color = 0xFFFF;
    break;
  default:
    break;
  }

  display_draw_raw_panic(title,
                         details ? details : "NO SYSTEM DETAILS PROVIDED", icon,
                         bg_color, fg_color, font8x8_basic);

  while (1) {
    esp_cpu_wait_for_intr();
  }
}